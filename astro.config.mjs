import { readFileSync } from 'node:fs';
import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';
import starlightLinksValidator from 'starlight-links-validator';
import { mermaidAssets } from './src/plugins/mermaid.mjs';

// SITE_URL / BASE_PATH let the same build serve the custom domain (root) or a
// project page such as https://<org>.github.io/<repo>/. CI derives both from
// actions/configure-pages; local builds default to the custom domain root.
const site = process.env.SITE_URL || 'https://karakoram.dev';
const base = process.env.BASE_PATH || '/';
const absolute = (path) => new URL(`${base.replace(/\/?$/, '/')}${path}`, site).href;

// Generated by scripts/ingest-docs.mjs (npm "predev"/"prebuild").
const sidebarFile = new URL('./src/generated/sidebar.json', import.meta.url);
let sidebar;
try {
	sidebar = JSON.parse(readFileSync(sidebarFile, 'utf8'));
} catch {
	throw new Error('src/generated/sidebar.json is missing. Run `npm run ingest` (done automatically by `npm run dev` and `npm run build`).');
}

// Documentation pages moved by the control-plane/engine restructure; old URLs were linked publicly.
const movedDocs = {
	'user-guide/replica-sets': 'mongodb/replica-sets',
	'user-guide/sharding': 'mongodb/sharding',
	'user-guide/users-tls-access': 'mongodb/access-and-tls',
	'user-guide/scaling-and-upgrades': 'mongodb/operations',
	'user-guide/backups-and-restore': 'backups',
	'user-guide/rabbitmq': 'rabbitmq',
	'user-guide/elasticsearch': 'elasticsearch',
	'user-guide/namespaces': 'namespaces',
	'user-guide/monitoring': 'monitoring',
	'user-guide/rbac-and-auth': 'access-control',
	'user-guide/web-ui': 'web-ui',
	'user-guide/api': 'api',
	'user-guide/cli': 'cli',
};
const redirects = Object.fromEntries(
	Object.entries(movedDocs).map(([from, to]) => [`/docs/${from}/`, `${base.replace(/\/?$/, '/')}docs/${to}/`]),
);

export default defineConfig({
	site,
	base,
	trailingSlash: 'always',
	redirects,
	integrations: [
		mermaidAssets(base),
		starlight({
			title: 'Karakoram',
			description:
				'Self-hosted MongoDB, PostgreSQL, Supabase, RabbitMQ and Elasticsearch orchestration on infrastructure you run: Percona Server for MongoDB with Percona Backup for MongoDB, Percona PostgreSQL with Patroni and pgBackRest, modular Supabase, RabbitMQ clusters and the Elastic Stack, driven by one control plane on Zerops, Dokploy (experimental) or Nomad (experimental).',
			logo: { src: './src/assets/logo.svg' },
			favicon: '/favicon.svg',
			social: [{ icon: 'github', label: 'GitHub', href: 'https://github.com/KarakoramDev/Karakoram' }],
			customCss: ['./src/styles/starlight.css'],
			// Inline the mark with currentColor so it follows the theme (design-owned).
			components: { SiteTitle: './src/components/StarlightSiteTitle.astro' },
			disable404Route: true,
			sidebar,
			head: [
				{ tag: 'link', attrs: { rel: 'apple-touch-icon', href: absolute('apple-touch-icon.png') } },
				{ tag: 'meta', attrs: { property: 'og:image', content: absolute('og.png') } },
				{ tag: 'meta', attrs: { property: 'og:image:width', content: '1200' } },
				{ tag: 'meta', attrs: { property: 'og:image:height', content: '630' } },
				{ tag: 'meta', attrs: { name: 'twitter:image', content: absolute('og.png') } },
			],
			plugins: [starlightLinksValidator({ errorOnRelativeLinks: true, errorOnInvalidHashes: true })],
		}),
	],
});
