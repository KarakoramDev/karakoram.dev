import { readFileSync } from 'node:fs';
import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';
import starlightLinksValidator from 'starlight-links-validator';
import starlightLlmsTxt from 'starlight-llms-txt';
import { mermaidAssets } from './src/plugins/mermaid.mjs';
import { brandIcons } from './src/plugins/brand-icons.mjs';

// SITE_URL / BASE_PATH let the same build serve the custom domain (root) or a
// project page such as https://<org>.github.io/<repo>/. CI derives both from
// actions/configure-pages; local builds default to the custom domain root.
const site = process.env.SITE_URL || 'https://karakoram.dev';
const base = process.env.BASE_PATH || '/';
const absolute = (path) => new URL(`${base.replace(/\/?$/, '/')}${path}`, site).href;

// Generated by scripts/ingest-docs.mjs (npm "predev"/"prebuild").
const generated = (name) => {
	try {
		return JSON.parse(readFileSync(new URL(`./src/generated/${name}`, import.meta.url), 'utf8'));
	} catch {
		throw new Error(`src/generated/${name} is missing. Run \`npm run ingest\` (done automatically by \`npm run dev\` and \`npm run build\`).`);
	}
};
const sidebar = generated('sidebar.json');
// Architecture decision records are no longer published here; their former URLs go to the code repository.
const adrRedirects = generated('adr-redirects.json');

// Keep the machine-readable entrypoint in sync with the generated navigation.
const sidebarMarkdown = (items, depth = 0) => items.map((item) => {
	const indent = '  '.repeat(depth);
	if (item.items) return `${indent}- **${item.label}**\n${sidebarMarkdown(item.items, depth + 1)}`;
	return `${indent}- [${item.label}](${absolute(`${item.slug}/`)})`;
}).join('\n');

// Documentation pages moved by the control-plane/engine restructure and the provider and operating-costs renames; old URLs were linked publicly.
const movedDocs = {
	pricing: 'operating-costs',
	backends: 'providers',
	'user-guide/replica-sets': 'mongodb/replica-sets',
	'user-guide/sharding': 'mongodb/sharding',
	'user-guide/users-tls-access': 'mongodb/access-and-tls',
	'user-guide/scaling-and-upgrades': 'mongodb/operations',
	'user-guide/backups-and-restore': 'backups',
	'user-guide/rabbitmq': 'rabbitmq',
	'user-guide/elasticsearch': 'elasticsearch',
	'user-guide/namespaces': 'namespaces',
	'user-guide/monitoring': 'monitoring',
	'user-guide/rbac-and-auth': 'access-control',
	'user-guide/web-ui': 'web-ui',
	'user-guide/api': 'api',
	'user-guide/cli': 'cli',
};
const redirects = {
	...Object.fromEntries(Object.entries(movedDocs).map(([from, to]) => [`/docs/${from}/`, `${base.replace(/\/?$/, '/')}docs/${to}/`])),
	...adrRedirects,
};

export default defineConfig({
	site,
	base,
	trailingSlash: 'always',
	redirects,
	integrations: [
		mermaidAssets(base),
		brandIcons(),
		starlight({
			title: 'Karakoram',
			description:
				'Self-hosted database and stateful-service orchestration on infrastructure you run: Zerops, Dokploy or Nomad.',
			logo: { src: './src/assets/logo.svg' },
			favicon: '/favicon.svg',
			social: [{ icon: 'github', label: 'GitHub', href: 'https://github.com/KarakoramDev/Karakoram' }],
			customCss: ['./src/styles/starlight.css'],
			// Inline the mark with currentColor so it follows the theme (design-owned); brand marks
			// (src/lib/brands.mjs) in the sidebar and in engine/provider page titles.
			components: {
				SiteTitle: './src/components/StarlightSiteTitle.astro',
				Head: './src/components/StarlightHead.astro',
				Sidebar: './src/components/StarlightSidebar.astro',
				PageTitle: './src/components/StarlightPageTitle.astro',
			},
			disable404Route: true,
			sidebar,
			head: [
				{ tag: 'link', attrs: { rel: 'apple-touch-icon', href: absolute('apple-touch-icon.png') } },
				{ tag: 'meta', attrs: { property: 'og:image', content: absolute('og.png') } },
				{ tag: 'meta', attrs: { property: 'og:image:width', content: '1200' } },
				{ tag: 'meta', attrs: { property: 'og:image:height', content: '630' } },
				{ tag: 'meta', attrs: { name: 'twitter:image', content: absolute('og.png') } },
			],
			plugins: [
				starlightLlmsTxt({
					projectName: 'Karakoram',
					description: 'Karakoram is an Apache-2.0, self-hosted control plane for databases and stateful services on infrastructure you run: Zerops (the reference provider), Dokploy or Nomad. It orchestrates databases, message brokers, search, identity, secrets and workflow engines; see the engine guides for capabilities and provider availability. It provides a REST API, the karactl CLI, a web UI and a read-only-by-default MCP server for AI agents, plus an opt-in per-cluster data MCP gateway. Documentation covers installation, providers, operating costs, cluster and fleet operations, backups and backup drills, control-plane backup and rebuild, notifications, access control, security and MCP client setup.',
					details: `Documentation sections and pages:\n\n${sidebarMarkdown(sidebar)}`,
				}),
				starlightLinksValidator({ errorOnRelativeLinks: true, errorOnInvalidHashes: true }),
			],
		}),
	],
});
